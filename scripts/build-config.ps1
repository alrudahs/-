# Generates amplitude-config.js from .env (browser pages cannot read .env directly).
# Only the public API key and server zone are written. The secret key is never exported.
# Usage (from the project folder, in PowerShell):  .\scripts\build-config.ps1
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'
if (-not (Test-Path $envFile)) { throw ".env not found. Copy .env.example to .env and fill in the values." }

$vars = @{}
foreach ($line in [System.IO.File]::ReadAllLines($envFile, [System.Text.Encoding]::UTF8)) {
  if ($line -match '^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$') { $vars[$matches[1]] = $matches[2].Trim() }
}

$apiKey = $vars['AMPLITUDE_API_KEY']
if (-not $apiKey) { throw "AMPLITUDE_API_KEY is empty in .env" }
$zone = if ($vars['AMPLITUDE_SERVER_ZONE'] -eq 'EU') { 'EU' } else { 'US' }

$js = @"
// Auto-generated by scripts/build-config.ps1 from .env - do not edit by hand.
// The Amplitude API key is a public, browser-side identifier. Never put the secret key here.
window.AMPLITUDE_CONFIG = { apiKey: '$apiKey', serverZone: '$zone' };
"@
$out = Join-Path $root 'amplitude-config.js'
[System.IO.File]::WriteAllText($out, $js + "`n", (New-Object System.Text.UTF8Encoding $false))
"Wrote $out (serverZone=$zone)"
